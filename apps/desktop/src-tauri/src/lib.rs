//! Оболочка рабочего стола (001 T112-T115).
//!
//! Всё содержательное — команды поверх `typsidian-core` — живёт в
//! `packages/shell` и общее с мобильной оболочкой. Здесь остаётся ровно то, что
//! у каждой оболочки своё: раскрытие `generate_context!()`, а с ним свой
//! `tauri.conf.json` (идентификатор `dev.typsidian.desktop`, размеры окна,
//! bundle), свои иконки, свои capabilities — и свой набор плагинов.

/// Точка входа оболочки.
pub fn run() {
    typsidian_shell::builder()
        // Нативный диалог выбора папки (T115). Подключается здесь, а не в общем
        // крейте: право `dialog:allow-open` из `capabilities/default.json`
        // существует только потому, что плагин записан в зависимости **этой**
        // оболочки. На Android папку выбирать нечем, и там плагина нет вовсе.
        .plugin(tauri_plugin_dialog::init())
        .run(tauri::generate_context!())
        .expect("оболочка Typsidian должна запуститься");
}
