pub fn allowed(command: &str) -> bool {
    ALLOWED.contains(&command)
}

#[cfg(test)]
mod tests {
    use super::*;
    use typsidian_host::dispatch::COMMANDS;

    #[test]
    fn allowed_commands_exist() {
        for name in ALLOWED {
            assert!(
                COMMANDS.contains(name)
                    || [
                        "attachments_batch_store",
                        "vault_reindex_properties",
                        "sync_open"
                    ]
                    .contains(name),
                "{name}"
            );
        }
    }

    #[test]
    fn device_and_paths_are_not_allowed() {
        for name in [
            "root_path",
            "open_vault",
            "browse_dir",
            "import_open_source",
            "import_survey",
            "device_settings",
            "apply_device_settings",
            "sync_syncthing_connect",
            "sync_syncthing_discover",
            "sync_clone_vault",
        ] {
            assert!(!allowed(name), "{name}");
        }
    }
}
