import type { TextEdit } from "../../wasm-core/typsidian_core.js";

// Порт правки открытой заметки (фича 013, contracts/editor-edit-port.md) —
// граница гейта принципа V. Панель связей меняет текст открытой заметки
// только через него: что и на что заменить, считает ядро (`plan_link`), порт
// лишь применяет готовую замену.
//
// Обязательства любой реализации:
// 1. Замена — одна единица истории отмены; прежние правки пользователя
//    остаются откатываемыми.
// 2. Курсор и выделение пользователя к месту замены не переносятся, фокус не
//    отбирается.
// 3. Правка идёт обычным путём редактора: буфер объявляется ядру, файл пишет
//    автосохранение в свой срок. Порт сам на диск не пишет.
// 4. Замена применяется к тому тексту, который вернул `textOf`; если текст
//    успел измениться, ответ — `NoEditor`, а не правка со сдвигом.
//
// Реализация поверх редакторов заметок — `plainEditors.ts`.

export interface OpenNoteEditors {
  /** Текст заметки в редакторе; `null` — заметка в редакторе не открыта. */
  textOf(path: string): string | null;
  /** Применить готовую замену из ядра (`LinkOutcome.EditorEdit`). */
  applyEdit(path: string, edit: TextEdit): { ok: true } | { ok: false; error: "NoEditor" };
}
