"use client";

import type { RenderedPage, TextRun } from "../wasm-core/typsidian_core.js";

// Принцип I: слой ничего не вычисляет. Где стоит прогон, какой он ширины и на
// каком языке — всё посчитано ядром из свёрстанного кадра
// (`preview::textlayer`, contracts/text-layer.md). Здесь только разметка.

/**
 * Выделяемый текст поверх картинки страницы (FR-031, FR-032, SC-011).
 *
 * `typst_svg` рисует каждый глиф контуром `<path>`: элемента `<text>` в выводе
 * нет вовсе, поэтому из самой картинки нельзя ни выделить текст, ни
 * скопировать его, ни прочитать программой чтения с экрана. Отсюда второй
 * слой — настоящий текст, невидимый, положенный поверх изображения, как в
 * просмотрщиках PDF.
 *
 * # Почему слой на SVG, а не на `<div>` с абсолютными координатами
 *
 * Координаты приходят в пунктах страницы, а лист на экране резиновый:
 * масштабируется и ступенями зума, и шириной колонки. У SVG для этого есть
 * `viewBox` — браузер сам пересчитывает и позиции, и кегль одним и тем же
 * множителем, тем самым, что применён к картинке. Слой на `<div>` требовал бы
 * своего множителя в JS, и он разъезжался бы с картинкой на каждом изменении
 * ширины панели.
 *
 * Второе следствие того же выбора: `y` у `<text>` — это базовая линия, ровно
 * то, что отдаёт ядро. Пересчёта в «верх строки» не нужно, а значит неоткуда и
 * взяться ошибке на величину подъёма шрифта.
 *
 * # Почему слой доступен вспомогательным технологиям
 *
 * Он **не** помечен `aria-hidden` и не объявлен декоративным — иначе FR-032
 * оказался бы нарушен ровно тем механизмом, который его выполняет.
 * Декоративной помечена картинка: текста она не несёт, и без пометки программа
 * чтения с экрана прочитала бы страницу дважды.
 */
export function TextLayer({ page }: { page: RenderedPage }): React.JSX.Element {
  return (
    <svg
      className="ts-textlayer"
      viewBox={`0 0 ${page.width_pt} ${page.height_pt}`}
      xmlns="http://www.w3.org/2000/svg"
    >
      {page.text_runs.map((run, index) => (
        <RunText key={index} run={run} />
      ))}
    </svg>
  );
}

function RunText({ run }: { run: TextRun }): React.JSX.Element {
  // `textLength` вгоняет невидимую строку ровно в ширину нарисованных глифов,
  // посчитанную ядром по `x_advance`. Без него подсветка выделения не совпала
  // бы с буквами: шрифт слоя — не тот, которым свёрстан документ, и своей
  // ширины у него другая. Нулевую ширину SVG считает недопустимой, поэтому
  // пустые прогоны идут без подгонки.
  const fitted = run.width_pt > 0;
  return (
    <text
      x={run.x_pt}
      y={run.y_pt}
      fontSize={run.size_pt}
      {...(run.lang ? { lang: run.lang } : {})}
      {...(fitted
        ? { textLength: run.width_pt, lengthAdjust: "spacingAndGlyphs" as const }
        : {})}
    >
      {run.text}
    </text>
  );
}
