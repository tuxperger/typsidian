import type { Capture } from "../wasm-core/typsidian_core.js";

/**
 * Откуда приходят захваты «Поделиться» и ярлыки приложения (фича 022).
 *
 * Платформенное, как `ShowHost` у показа слайдов: приём `ACTION_SEND` и
 * ярлыков Android недоступен ни из Rust, ни из JS без нативного кода, поэтому
 * источник приходит от оболочки пропом `captureSource` в `Workspace`. Нет
 * источника — приёма «Поделиться» нет, а команды «Во входящие» и «Сегодня»
 * работают во всех оболочках.
 *
 * Очередь живёт в памяти приложения на устройстве, а не в vault: vault может
 * быть недоступен. Запись остаётся в очереди, пока окно не вызвало `resolve`
 * (FR-005): отказ записи `resolve` не зовёт.
 */
export interface CaptureSource {
  /** Ждущие захваты в порядке поступления. */
  pending(): Promise<Capture[]>;
  /** Убрать запись из очереди: записана в vault либо пользователь отказался. */
  resolve(id: string): Promise<void>;
  /**
   * Вернуть пользователя в приложение, откуда он поделился (`moveTaskToBack`).
   * Ничего не делает, если приложение открыто не из «Поделиться».
   */
  returnToSource(): Promise<void>;
  /**
   * Байты картинки захвата `content.kind === "Image"`. `content.file` — путь к
   * файлу в памяти приложения; читает его источник, окно путей не открывает.
   */
  image(capture: Capture): Promise<Uint8Array>;
  /** В очереди появилась новая запись; возвращает функцию отписки. */
  onShared(handler: () => void): () => void;
  /** Ярлык приложения: «Сегодня» или «Во входящие»; возвращает функцию отписки. */
  onShortcut(handler: (action: "today" | "capture") => void): () => void;
}
